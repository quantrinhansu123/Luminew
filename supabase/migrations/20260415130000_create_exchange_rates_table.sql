ALTER TABLE public.exchange_rates ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all access to exchange_rates" ON public.exchange_rates;
CREATE POLICY "Allow all access to exchange_rates"
  ON public.exchange_rates
  FOR ALL
  TO authenticated, anon
  USING (true)
  WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.exchange_rates TO authenticated, anon;
GRANT USAGE, SELECT ON SEQUENCE public.exchange_rates_id_seq TO authenticated, anon;
