-- Create exchange_rates table for currency conversion management.

CREATE TABLE IF NOT EXISTS public.exchange_rates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ti_gia text NOT NULL,
  gia_tri numeric(12,2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_exchange_rates_ti_gia_unique
  ON public.exchange_rates (ti_gia);

CREATE INDEX IF NOT EXISTS idx_exchange_rates_ti_gia
  ON public.exchange_rates (ti_gia);

CREATE OR REPLACE FUNCTION public.update_exchange_rates_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trigger_update_exchange_rates_updated_at ON public.exchange_rates;
CREATE TRIGGER trigger_update_exchange_rates_updated_at
  BEFORE UPDATE ON public.exchange_rates
  FOR EACH ROW
  EXECUTE FUNCTION public.update_exchange_rates_updated_at();

